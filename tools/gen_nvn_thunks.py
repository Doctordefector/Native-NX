"""Generate guest-register thunks for the NVN implementations (src/gfx/nvn/nvn_thunks.gen.c).

The game calls NVN through function pointers it gets from nvnBootstrapLoader / nvnDeviceGetProcAddress. Each pointer is
a fake guest address of a host function on the guest registers (src/runtime: hle_register). This script reads the
implementations' own declarations (NVN / NVN_NOPROTO / NVN_EXTRA in src/gfx/nvn/*.c, MacNativeGames' macros) and the
types of include/nvn.h, and writes for each one a thunk that unpacks AAPCS64 arguments: integers, pointers, enums and
handles from x0..x7, float/double from v0..v7; the result goes to x0 (or v0 for float/double).
A structure passed or returned by value stops the generator: AAPCS64 passes those differently.

usage: python tools/gen_nvn_thunks.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
NVN = ROOT / 'src/gfx/nvn'
DECL = re.compile(r'^(NVN|NVN_NOPROTO|NVN_EXTRA)\((\w+),\s*([^,]+?),\s*(.*?)\)\s*\{', re.M | re.S)


SMALL = {}   # struct type -> True when it is a single integer field of at most 8 bytes (AAPCS64: one x register)


def struct_types():
    text = (NVN / 'include/nvn.h').read_text(encoding='utf-8', errors='replace')
    names = set()
    for body, name in re.findall(r'typedef struct\s*\w*\s*\{([^}]*)\}\s*(\w+)\s*;', text):
        names.add(name)
        fields = [f.strip() for f in body.split(';') if f.strip() and not f.strip().startswith('//')]
        if len(fields) == 1 and re.fullmatch(r'(u?int(8|16|32|64)_t)\s+\w+', fields[0]):
            SMALL[name] = True
    return names


def split_params(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip()); cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return [p for p in out if p and p != 'void']


def param_type(p):
    m = re.match(r'^(.*?)(\w+)$', p.strip())
    if not m or not m.group(1).strip():
        sys.exit(f'cannot parse parameter {p!r}')
    return m.group(1).strip()


def kind(t, structs):
    base = t.replace('const', '').strip()
    if '*' in base:
        return 'ptr'
    if base in ('float', 'double'):
        return base
    if base in SMALL:
        return 'small'
    if base in structs:
        return 'struct'
    return 'int'


def main():
    structs = struct_types()
    decls = {}
    for src in sorted(NVN.glob('*.c')):
        text = src.read_text(encoding='utf-8', errors='replace')
        for m in DECL.finditer(text):
            macro, name, ret, params = m.group(1), m.group(2), m.group(3).strip(), split_params(m.group(4))
            if name in decls and decls[name][1:] != (ret, params):
                sys.exit(f'{name}: two different declarations')
            decls[name] = (macro, ret, params)
    out = ['// Generated by tools/gen_nvn_thunks.py from the NVN implementations\' declarations. Do not edit.',
           '#include <string.h>', '#include "include/nvn.h"', '#include "../../runtime/cpu.h"',
           'void *nvn_impl_fn(const char *name, int extra);', '']
    table = []
    for name, (macro, ret, params) in sorted(decls.items()):
        rk = kind(ret, structs)
        if rk == 'struct':
            sys.exit(f'{name}: returns a structure by value')
        types = [param_type(p) for p in params]
        nx = nv = 0
        args = []
        for t in types:
            k = kind(t, structs)
            if k == 'struct':
                sys.exit(f'{name}: structure parameter by value ({t})')
            if k in ('float', 'double'):
                if nv >= 8: sys.exit(f'{name}: more than 8 FP arguments')
                args.append(f'({{ {k} v_; memcpy(&v_, &c->v[{nv}], sizeof v_); v_; }})')
                nv += 1
            else:
                if nx >= 8: sys.exit(f'{name}: more than 8 integer arguments (stack arguments are not handled)')
                if k == 'small':
                    args.append(f'({{ {t} v_; memcpy(&v_, &c->x[{nx}], sizeof v_); v_; }})')
                else:
                    args.append(f'(void *)(uintptr_t)c->x[{nx}]' if k == 'ptr' else f'({t})c->x[{nx}]')
                nx += 1
        # pointers are passed as void * (the same in both ABIs): extension types need not be visible here
        ptypes = ['void *' if kind(t, structs) == 'ptr' else t for t in types]
        rtype = 'void *' if rk == 'ptr' and ret not in ('PFNNVNGENERICFUNCPTRPROC',) else ret
        fnty = f'{rtype} (*)({", ".join(ptypes) or "void"})'
        call = f'(({fnty})f)({", ".join(args)})'
        out.append(f'static void T_{name}(Cpu *c) {{')
        out.append(f'    static void *f; if (!f) f = nvn_impl_fn("{name}", {int(macro == "NVN_EXTRA")});')
        if ret == 'void':
            out.append(f'    {call};')
        elif rk in ('float', 'double'):
            out.append(f'    {ret} r_ = {call}; memset(&c->v[0], 0, sizeof c->v[0]); memcpy(&c->v[0], &r_, sizeof r_);')
        elif rk == 'ptr':
            out.append(f'    c->x[0] = (uint64_t)(uintptr_t){call};')
        elif rk == 'small':   # a single-integer-field structure: returned in x0 (AAPCS64) / RAX (Win64)
            out.append(f'    {ret} r_ = {call}; uint64_t v_ = 0; memcpy(&v_, &r_, sizeof r_); c->x[0] = v_;')
        else:
            out.append(f'    c->x[0] = (uint64_t){call};')
        out.append('}')
        table.append(f'    {{"{name}", T_{name}}},')
    out.append('const struct { const char *name; void (*fn)(Cpu *); } nvn_thunks[] = {')
    out += table
    out.append('};')
    out.append(f'const unsigned nvn_thunk_count = {len(table)};')
    (NVN / 'nvn_thunks.gen.c').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'{len(table)} thunks -> {NVN / "nvn_thunks.gen.c"}')


if __name__ == '__main__':
    main()
