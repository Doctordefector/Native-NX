"""AArch32 SVC register maps, computed the way Atmosphere's codegen does (svc_codegen_impl_layout.hpp:
ProcedureLayout<Aarch32Ilp32Abi> -> SvcInvocationLayout<Aarch32SvcInvokeAbi>), from svc_definition_macro.hpp.

Prints C: for every SVC, which r registers hold each 64-bit-ABI argument (in order) and which hold each output.
Run: python tools/svc32_abi.py > runtime/svc32_tab.h
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PTR = 4
SIZE8 = {'uint64_t', 'int64_t', '::ams::svc::PhysicalAddress'}
PTRT = {'::ams::svc::Address', '::ams::svc::Size', '::ams::svc::ThreadFunc'}


def tsize(t):
    if t in SIZE8: return 8
    if t in PTRT: return PTR
    if t == 'bool': return 1
    if 'LastThreadContext' in t: return 16      # 4 u32 regs
    if 'SecureMonitorArguments' in t: return 64
    if 'PhysicalMemoryInfo' in t: return 24
    return 4                                      # u32, Handle, enums, PageInfo, Result


def integral(t):
    return t.startswith(('uint', 'int', 'bool')) or t in PTRT or t in SIZE8 or t == '::ams::svc::Handle'


def layout(params, ret):
    """params: [(kind, type)] kind in INPUT OUTPUT INPTR OUTPTR. returns (in_regs per param, out_regs per param)"""
    # ProcedureLayout<Aarch32Ilp32Abi>: register size 4, 4 argument registers
    NGRN, NSAA = 0, 0
    proc = []     # (idx, kind, type_size, by_ptr, [('r'|'s', i)...])
    for i, (k, t) in enumerate(params):
        ts = tsize(t)
        if k in ('OUTPUT', 'INPTR', 'OUTPTR'): by_ptr = True
        else: by_ptr = (not integral(t)) and ts > 4
        ps = PTR if by_ptr else ts
        if ps > 4: NGRN += NGRN & 1
        locs = []
        nreg = (ps + 3) // 4
        if not by_ptr and k == 'INPUT' and ts > 4:
            if 4 - NGRN >= 2: locs = [('r', NGRN), ('r', NGRN + 1)]; NGRN += 2
            else:
                NGRN = 4; NSAA += NSAA & 1; locs = [('s', NSAA), ('s', NSAA + 1)]; NSAA += 2
        elif ps <= 4 * (4 - NGRN):
            locs = [('r', NGRN + j) for j in range(nreg)]; NGRN += nreg
        else:
            NGRN = 4; locs = [('s', NSAA + j) for j in range(nreg)]; NSAA += nreg
        argtype = {'INPUT': 'In', 'OUTPUT': 'Out', 'INPTR': 'InUser', 'OUTPTR': 'OutUser'}[k]
        proc.append(dict(i=i, type=argtype, ts=ts, by_ptr=by_ptr and k == 'INPUT', locs=locs))
    # SvcInvocationLayout<Aarch32SvcInvokeAbi>: register size 4, 8 registers
    used = [False] * 8
    inp = {}

    def first_free():
        for r in range(8):
            if not used[r]: used[r] = True; return r
        raise RuntimeError('out of registers')
    order = sorted(proc, key=lambda p: (p['locs'][0][0] == 's', p['locs'][0][1]) if p['locs'] else (2, 0))
    # ForEachInputArgument sorts by GetLocation(0) (storage then index: Register < Stack)
    sel = lambda p: (p['type'] == 'In' and not p['by_ptr'])
    groups = [lambda p: sel(p), lambda p: p['type'] == 'InUser', lambda p: p['type'] == 'OutUser']
    for g in groups:                               # registers -> same registers
        for p in order:
            if g(p):
                for s, r in p['locs']:
                    if s == 'r':
                        assert not used[r]; used[r] = True; inp.setdefault(p['i'], []).append(r)
    for g in groups:                               # stack -> first free registers
        for p in order:
            if g(p):
                for s, r in p['locs']:
                    if s == 's': inp.setdefault(p['i'], []).append(first_free())
    for p in proc:                                 # by-pointer inputs -> registers holding the value
        if p['type'] == 'In' and p['by_ptr']:
            for _ in range(0, p['ts'], 4): inp.setdefault(p['i'], []).append(first_free())
    oused = [False] * 8
    out = {}
    if ret != 'void': oused[0] = True
    for p in proc:
        if p['type'] == 'Out':
            for _ in range(0, p['ts'], 4):
                r = oused.index(False); oused[r] = True; out.setdefault(p['i'], []).append(r)
    return inp, out


def parse():
    src = open(os.path.join(HERE, 'svc_definition_macro.hpp'), encoding='utf-8').read()
    src = src.split('AMS_SVC_FOREACH_DEFINITION_IMPL', 1)[1]
    res = {}
    for m in re.finditer(r'HANDLER\((0x[0-9A-F]+),\s*(\w+),\s*(\w+)\s*(?:,(.*?))?\)\s*\\', src):
        num = int(m.group(1), 16); ret = m.group(2); name = m.group(3)
        if name.startswith('Legacy'): continue
        params = re.findall(r'(INPUT|OUTPUT|INPTR|OUTPTR)\(([^,]+),\s*\w+\)', m.group(4) or '')
        res[num] = (name, ret, [(k, t.strip()) for k, t in params])
    return res


def main():
    defs = parse()
    print('/* generated by tools/svc32_abi.py from Atmosphere svc_definition_macro.hpp: do not edit */')
    print('/* per SVC: for each 64-bit-ABI parameter, the r registers it arrives in (lo, hi) or is returned in; -1 none */')
    print('typedef struct { const char* name; signed char r[8][2]; unsigned char np, isout[8]; } Svc32Abi;')
    print('static const Svc32Abi g_svc32[0x80]={')
    for num in sorted(defs):
        if num >= 0x80: continue
        name, ret, params = defs[num]
        if any(tsize(t) > 16 for k, t in params): continue   # CallSecureMonitor: not for games
        inp, out = layout(params, ret)
        isout = ['1' if k == 'OUTPUT' else '0' for k, t in params]
        # keep both lists in parameter order: in[] for inputs, out[] for outputs (skipped slots unused)
        allp = []
        for i, (k, t) in enumerate(params):
            r = inp.get(i, []) if k != 'OUTPUT' else out.get(i, [])
            allp.append('{%d,%d}' % tuple((r + [-1, -1])[:2]))
        print('  [0x%02X]={"%s",{%s},%d,{%s}},' % (num, name, ','.join(allp) or '{-1,-1}', len(params), ','.join(isout) or '0'))
    print('};')


if __name__ == '__main__':
    main()
